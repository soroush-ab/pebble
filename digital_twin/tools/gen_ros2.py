#!/usr/bin/env python3
"""Generate the ROS 2 description package from the CAD bake.

    python3 tools/gen_ros2.py

Writes ros2_ws/src/pebble_description/{urdf/pebble.urdf, meshes/*.stl} from
config/urdf_derived.json. Everything else in the workspace is hand-written.

Why a URDF works here even though the real neck is a closed chain: the baked
model is already a serial tree (base -> yaw -> roll -> pitch). The pushrod
linkage is abstracted BELOW the pitch/roll joints - exactly as the firmware
will treat it - so there is nothing for URDF to fail to express. The pushrods
themselves are frozen into the yaw body and do not animate. That is the
honest limit of this model, and it is stated in the generated URDF too.
"""

import json
import math
import os
import shutil

import numpy as np
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = os.path.join(ROOT, "ros2_ws", "src", "pebble_description")


def rpy_from_R(R):
    """URDF fixed-axis roll-pitch-yaw from a rotation matrix (R = Rz*Ry*Rx).

    The roll joint's frame sits at pitch ~= 90 deg, i.e. near gimbal lock, so
    this decomposition is ill-conditioned there. It still round-trips to about
    4e-6 rad (0.0002 deg) - orders of magnitude below servo resolution - but
    main() checks the residual rather than assuming it.
    """
    sy = math.hypot(R[0, 0], R[1, 0])
    if sy < 1e-12:                                  # true gimbal lock
        return math.atan2(-R[1, 2], R[1, 1]), math.atan2(-R[2, 0], sy), 0.0
    return (math.atan2(R[2, 1], R[2, 2]),
            math.atan2(-R[2, 0], sy),
            math.atan2(R[1, 0], R[0, 0]))


def R_from_rpy(r, p, y):
    cr, sr, cp, sp, cy, sy = (math.cos(r), math.sin(r), math.cos(p),
                              math.sin(p), math.cos(y), math.sin(y))
    return np.array([[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
                     [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
                     [-sp,     cp * sr,                cp * cr]])


def fmt(v):
    return " ".join(f"{float(x):.9g}" for x in v)


def main():
    derived = json.load(open(os.path.join(ROOT, "config", "urdf_derived.json")))
    robot = yaml.safe_load(open(os.path.join(ROOT, "config", "robot.yaml")))

    os.makedirs(os.path.join(PKG, "urdf"), exist_ok=True)
    mesh_out = os.path.join(PKG, "meshes")
    os.makedirs(mesh_out, exist_ok=True)

    src_meshes = os.path.join(ROOT, "twin", "web", "meshes")
    for g in derived["groups"].values():
        for fn in g.values():
            shutil.copy2(os.path.join(src_meshes, fn), os.path.join(mesh_out, fn))

    chain = derived["chain"]                        # base, yaw, roll, pitch
    # map semantic DOF -> the joint config in robot.yaml
    JCFG = {"yaw": "base_yaw", "roll": "head_roll", "pitch": "head_pitch"}

    L = []
    L.append('<?xml version="1.0"?>')
    L.append('<!-- GENERATED by tools/gen_ros2.py from config/urdf_derived.json.')
    L.append('     Do not hand-edit: re-run the tool after any CAD change.')
    L.append('')
    L.append('     The real neck is a PARALLEL pushrod mechanism. This URDF models')
    L.append('     the head pose (roll, pitch) as serial joints, which is what the')
    L.append('     motion layer and the firmware both command; twin/linkage.py maps')
    L.append('     pose -> the two MG995 servo angles below this abstraction.')
    L.append('     The pushrods are frozen into the yaw body and do not animate. -->')
    L.append(f'<robot name="{robot["name"]}">')

    L.append('')
    L.append('  <material name="shell"><color rgba="0.85 0.87 0.90 1"/></material>')
    L.append('  <material name="internal"><color rgba="0.22 0.25 0.30 1"/></material>')

    # floor frame so z=0 is the ground plane
    zmin = derived["bbox"]["min"][2]
    L.append('')
    L.append('  <link name="base_footprint"/>')
    L.append('  <joint name="base_footprint_joint" type="fixed">')
    L.append('    <parent link="base_footprint"/>')
    L.append('    <child link="base_link"/>')
    L.append(f'    <origin xyz="0 0 {-zmin:.9g}" rpy="0 0 0"/>')
    L.append('  </joint>')

    linkname = {"base": "base_link", "yaw": "yaw_link",
                "roll": "roll_link", "pitch": "head_link"}

    for g in chain:
        L.append('')
        L.append(f'  <link name="{linkname[g]}">')
        for kind, fn in sorted(derived["groups"].get(g, {}).items()):
            L.append('    <visual>')
            L.append('      <origin xyz="0 0 0" rpy="0 0 0"/>')
            L.append('      <geometry>')
            L.append(f'        <mesh filename="package://pebble_description/meshes/{fn}"/>')
            L.append('      </geometry>')
            L.append(f'      <material name="{kind}"/>')
            L.append('    </visual>')
            L.append('    <collision>')
            L.append('      <origin xyz="0 0 0" rpy="0 0 0"/>')
            L.append('      <geometry>')
            L.append(f'        <mesh filename="package://pebble_description/meshes/{fn}"/>')
            L.append('      </geometry>')
            L.append('    </collision>')
        L.append('  </link>')

    worst_rpy_err = 0.0
    for i, g in enumerate(chain[1:], start=1):
        j = derived["joints"][g]
        T = np.array(j["origin_matrix"]).reshape(4, 4).T
        xyz = T[:3, 3]
        R = T[:3, :3]
        if not np.allclose(R.T @ R, np.eye(3), atol=1e-6) or np.linalg.det(R) < 0:
            raise SystemExit(f"{g}: baked rotation is not a proper rotation")
        rpy = rpy_from_R(R)
        # the URDF carries rpy, so confirm it reconstructs the baked transform
        err = float(np.abs(R_from_rpy(*rpy) - R).max())
        worst_rpy_err = max(worst_rpy_err, err)
        if err > 1e-4:                              # ~0.006 deg, still generous
            raise SystemExit(f"{g}: rpy round-trip error {err:.2e} too large")

        cfg = robot["joints"][JCFG[g]]
        lo = math.radians(float(cfg["min_deg"]))
        hi = math.radians(float(cfg["max_deg"]))
        vel = math.radians(float(cfg["max_vel_dps"]))
        L.append('')
        L.append(f'  <!-- {j["urdf_joint"]} in the Fusion export -->')
        L.append(f'  <joint name="{JCFG[g]}" type="revolute">')
        L.append(f'    <parent link="{linkname[chain[i-1]]}"/>')
        L.append(f'    <child link="{linkname[g]}"/>')
        L.append(f'    <origin xyz="{fmt(xyz)}" rpy="{fmt(rpy)}"/>')
        L.append(f'    <axis xyz="{fmt(j["axis_local"])}"/>')
        L.append(f'    <limit lower="{lo:.6f}" upper="{hi:.6f}" '
                 f'effort="5" velocity="{vel:.4f}"/>')
        L.append('  </joint>')

    # eye frames, so RViz can show where the displays point
    for n, disp in enumerate(derived["displays"]):
        M = np.array(disp["face_matrix"]).reshape(4, 4).T
        rpy = rpy_from_R(M[:3, :3])
        L.append('')
        L.append(f'  <link name="eye_{n}_link"/>')
        L.append(f'  <joint name="eye_{n}_joint" type="fixed">')
        L.append(f'    <parent link="{linkname[chain[-1]]}"/>')
        L.append(f'    <child link="eye_{n}_link"/>')
        L.append(f'    <origin xyz="{fmt(M[:3, 3])}" rpy="{fmt(rpy)}"/>')
        L.append('  </joint>')

    L.append('')
    L.append('</robot>')

    out = os.path.join(PKG, "urdf", "pebble.urdf")
    with open(out, "w") as fh:
        fh.write("\n".join(L) + "\n")

    print(f"wrote {os.path.relpath(out, ROOT)}")
    print(f"  links  : base_footprint + {len(chain)} bodies + "
          f"{len(derived['displays'])} eye frames")
    print(f"  joints : {', '.join(JCFG[g] for g in chain[1:])} (revolute)")
    print(f"  meshes : {len(os.listdir(mesh_out))} copied to "
          f"{os.path.relpath(mesh_out, ROOT)}")
    print(f"  worst rpy round-trip error: {worst_rpy_err:.2e} "
          f"({math.degrees(worst_rpy_err):.6f} deg)")


if __name__ == "__main__":
    main()
